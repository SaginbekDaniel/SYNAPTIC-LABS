// Generates src/data/qr.ts: a QR code for the public repository as one SVG path (no runtime dependency).
// Usage: node scripts/gen-qr.mjs
import { writeFileSync } from "node:fs";
import QRCode from "qrcode";

// Must equal REPO_URL in src/data/links.ts (a unit test checks it).
const URL = "https://github.com/SaginbekDaniel/SYNAPTIC-LABS";
const qr = QRCode.create(URL, { errorCorrectionLevel: "M" });
const { size, data } = qr.modules;
let d = "";
for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) if (data[y * size + x]) d += `M${x} ${y}h1v1h-1z`;
writeFileSync(
  "src/data/qr.ts",
  `// Generated by scripts/gen-qr.mjs — do not edit.\nexport const QR = { url: ${JSON.stringify(URL)}, size: ${size}, path: ${JSON.stringify(d)} } as const;\n`,
);
console.log("wrote src/data/qr.ts", size);
